const DICTS: Record<Lang, Dict> = { zh: {}, "zh-TW": zhTW, en, ja, es };

const ALL: Lang[] = ["zh", "zh-TW", "en", "ja", "es"];

/** The language Windows is set to, mapped onto one of ours. */
export function systemLang(): Lang {
  const nav =
    typeof navigator !== "undefined"
      ? navigator.language || (navigator.languages && navigator.languages[0]) || ""
      : "";
  return normalizeLocale(nav);
}

/** Map a BCP-47 tag (e.g. `zh-Hans-CN`) onto a supported language. */
function normalizeLocale(raw: string): Lang {
  const low = raw.toLowerCase().replace("_", "-");
  if (!low) return "en";
  if (low === "zh" || low.startsWith("zh-cn") || low.startsWith("zh-hans") || low.startsWith("zh-sg")) {
    return "zh";
  }
  if (low.startsWith("zh")) return "zh-TW";
  if (low.startsWith("ja")) return "ja";
  if (low.startsWith("es")) return "es";
  if (low.startsWith("en")) return "en";
  return ALL.includes(low as Lang) ? (low as Lang) : "en";
}

/**
 * Normalise anything coming from settings / the OS into a supported language.
 *
 * The special value `system` (the "follow Windows" option) resolves to the OS
 * language, so callers never have to branch on it.
 */
export function normalizeLang(value: unknown): Lang {
  const raw = String(value ?? "").trim();
  if (!raw) return "en";
  if (raw.toLowerCase() === "system") return systemLang();
  return normalizeLocale(raw);
}

let current: Lang = "en";
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(value: unknown): void {
  const next = normalizeLang(value);
  if (next === current) return;
  current = next;
  listeners.forEach((fn) => fn());
}

export function subscribeLang(fn: () => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/** Re-render a component whenever the interface language changes. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribeLang, getLang, getLang);
}

/**
 * Translate `key`. `vars` replaces `{name}` placeholders.
 * Unknown keys fall back to the key itself (readable Chinese).
 */
export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[current] || {};
  let out = dict[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      out = out.split(`{${k}}`).join(String(vars[k]));
    }
  }
  return out;
}
